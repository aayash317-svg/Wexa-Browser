import json
import logging
from pathlib import Path
from typing import Optional, Dict, Any
from backend.config import settings

logger = logging.getLogger(__name__)

class EmbeddedInferenceEngine:
    """
    Embedded local model runner using llama.cpp / GGUF.
    Runs strictly in-process without requiring an external Ollama daemon.
    """
    def __init__(self, model_filename: Optional[str] = None):
        self.model_filename = model_filename or settings.DEFAULT_GGUF_MODEL
        self.model_path = settings.MODELS_DIR / self.model_filename
        self.llm = None
        self._load_model()

    def _load_model(self):
        if not self.model_path.exists():
            logger.warning(
                f"GGUF model not found at {self.model_path}. "
                "Embedded engine initialized in mock/standby mode until GGUF weights are downloaded."
            )
            return

        try:
            from llama_cpp import Llama
            logger.info(f"Loading embedded GGUF model: {self.model_path}")
            self.llm = Llama(
                model_path=str(self.model_path),
                n_ctx=settings.CONTEXT_WINDOW,
                n_threads=settings.N_THREADS,
                verbose=False
            )
            logger.info("Embedded model loaded successfully.")
        except ImportError:
            logger.warning(
                "llama-cpp-python is not yet installed in this environment. "
                "Engine running in development fallback mode."
            )
        except Exception as e:
            logger.error(f"Failed to load model from {self.model_path}: {e}")

    @property
    def is_ready(self) -> bool:
        return self.llm is not None

    def generate(self, prompt: str, max_tokens: int = 512, temperature: float = 0.2) -> str:
        """Raw text generation."""
        if self.llm:
            output = self.llm(
                prompt,
                max_tokens=max_tokens,
                temperature=temperature,
                stop=["<|im_end|>", "```\n\n", "User:"]
            )
            return output["choices"][0]["text"].strip()
        
        # Development fallback response when weights are not yet downloaded
        return (
            "# [Fallback Code Generator - Model weights pending in models/]\n"
            "def solve(*args, **kwargs):\n"
            "    # TODO: Implement solution logic\n"
            "    return True"
        )

    def generate_code_patch(self, problem: str, starter_code: str, language: str) -> Dict[str, Any]:
        """
        Specialized coding prompt generating targeted completion.
        """
        system_instruction = (
            "You are Wexa Coder, a precision page-aware coding model. "
            "Write ONLY the exact missing code block. Do NOT rewrite surrounding boilerplate. "
            "Preserve function names and signatures exactly."
        )
        
        prompt = (
            f"<|im_start|>system\n{system_instruction}<|im_end|>\n"
            f"<|im_start|>user\n"
            f"Language: {language}\n"
            f"Problem Statement:\n{problem}\n\n"
            f"Starter Code:\n```{language}\n{starter_code}\n```\n\n"
            f"Complete the missing implementation:<|im_end|>\n"
            f"<|im_start|>assistant\n"
        )
        
        raw_code = self.generate(prompt)
        # Strip markdown fences if present
        if raw_code.startswith("```"):
            lines = raw_code.splitlines()
            if len(lines) >= 2 and lines[-1].startswith("```"):
                raw_code = "\n".join(lines[1:-1]).strip()

        return {
            "proposed_code": raw_code,
            "explanation": "Targeted solution implementation generated by embedded Wexa model."
        }
